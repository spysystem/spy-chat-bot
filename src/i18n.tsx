const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = {en, da};

/**
 * Progress statuses are produced in English by the main process (claude-service.ts / claude-tools.ts).
 * Known ones are translated here; anything else is shown as-is.
 */
const DANISH_PROGRESS: Array<[RegExp, string]> = [
	[/^Preparing\.\.\.$/, 'Forbereder…'],
	[/^Processing\.\.\.$/, 'Arbejder…'],
	[/^Stopping\.\.\.$/, 'Stopper…'],
	[/^Jørgen is thinking\.\.\.$/, 'Jørgen tænker…'],
	[/^Reading web page\.\.\.$/, 'Læser webside…'],
	[/^Searching the web\.\.\.$/, 'Søger på nettet…'],
	[/^Searching Sentry\.\.\.$/, 'Søger i Sentry…'],
	[/^Using (.+)\.\.\.$/, 'Bruger $1…'],
	[/^Searching schema: (.*)$/, 'Søger i databaseskemaet: $1'],
	[/^Reading table structure: (.*)$/, 'Læser tabelstruktur: $1'],
	[/^Running query: (.*)$/, 'Kører forespørgsel: $1'],
	[/^Exporting CSV: (.*)$/, 'Eksporterer CSV: $1'],
	[/^Searching code index: (.*)$/, 'Søger i kodeindekset: $1'],
	[/^Searching code: (.*)$/, 'Søger i koden: $1'],
	[/^Reading history of (.*)$/, 'Læser historik for $1'],
	[/^Reading commit (.*)$/, 'Læser commit $1'],
	[/^Reading Sentry issue (.*)$/, 'Læser Sentry-fejl $1'],
	[/^Comparing (.*) and (.*)$/, 'Sammenligner $1 og $2'],
	[/^Reading (.*)$/, 'Læser $1'],
];

interface I18nContextValue {
	language: Language;
	setLanguage: (language: Language) => void;
	t: (key: TranslationKey, params?: Record<string, string | number>) => string;
	/** Locale for dates and times. */
	locale: string;
	translateProgress: (status: string) => string;
	/** The main process names new chats "New Chat"; show that default in the chosen language. */
	chatTitle: (title: string | undefined) => string;
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

function loadLanguage(): Language {
	const saved = localStorage.getItem('language');
	return saved === 'en' || saved === 'da' ? saved : 'da';
}

export function LanguageProvider({children}: { children: ReactNode }): JSX.Element {
	const [language, setLanguage] = useState<Language>(loadLanguage);

	useEffect(() => {
		document.documentElement.lang = language;
		localStorage.setItem('language', language);
	}, [language]);

	const value = useMemo<I18nContextValue>(() => {
		const dictionary = DICTIONARIES[language];
		return {
			language,
			setLanguage,
			locale           : language === 'da' ? 'da-DK' : 'en-GB',
			t                : (key, params) => {
				let text = dictionary[key];
				for (const [name, replacement] of Object.entries(params ?? {})) {
					text = text.split(`{${name}}`).join(String(replacement));
				}
				return text;
			},
			chatTitle        : (title) => (!title || title === 'New Chat' ? dictionary['chat.newChat'] : title),
			translateProgress: (status) => {
				if (language === 'en') {
					return status;
				}
				const match = DANISH_PROGRESS.find(([pattern]) => pattern.test(status));
				return match ? status.replace(match[0], match[1]) : status;
			},
		};
	}, [language]);

	return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
	const context = useContext(I18nContext);
	if (context === undefined) {
		throw new Error('useI18n must be used within a LanguageProvider');
	}
	return context;
}
